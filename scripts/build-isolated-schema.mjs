import { readFileSync, readdirSync, writeFileSync } from "node:fs";
const files = readdirSync(new URL("../supabase/migrations/", import.meta.url))
  .filter((f) => f.endsWith(".sql"))
  .sort();
const source = files
  .map((file) => readFileSync(new URL("../supabase/migrations/" + file, import.meta.url), "utf8"))
  .join("\n");
// Preserve the PUBLIC role. Only schema-qualified object names and schema grants are changed.
const isolated = source
  .replace(/\bpublic\./g, "leadtrace.")
  .replace(/\bschema public\b/g, "schema leadtrace")
  .replace(/\bprivate\./g, "leadtrace_private.")
  .replace(/\bschema private\b/g, "schema leadtrace_private")
  .replace(/\bschema if not exists private\b/g, "schema if not exists leadtrace_private");
const header = `-- Generated by npm run db:isolated. Apply this OR the public-schema migration, never both.\n-- Existing public tables/policies/grants are not changed. Auth and infrastructure remain shared.\ncreate schema if not exists leadtrace;\nrevoke all on schema leadtrace from public,anon;\ngrant usage on schema leadtrace to authenticated,service_role;\n`;
writeFileSync(new URL("../supabase/isolated-schema.sql", import.meta.url), header + isolated);
const bootstrap = readFileSync(
  new URL("../supabase/bootstrap.sql", import.meta.url),
  "utf8",
).replace(/\bpublic\./g, "leadtrace.");
writeFileSync(
  new URL("../supabase/bootstrap-isolated.sql", import.meta.url),
  "-- Optional shared-project bootstrap. Use only after explicit project selection.\n" + bootstrap,
);
